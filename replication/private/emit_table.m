function emit_table(item,title,values,P,out)
% Full-precision numbers plus readable HTML and LaTeX; no external program.
writetable(values,fullfile(out,[item '.csv']));save(fullfile(out,[item '.mat']),'values','P');
f=fopen(fullfile(out,[item '.html']),'w');assert(f>0);c=onCleanup(@()fclose(f));
fprintf(f,'<!doctype html><meta charset="utf-8"><title>%s</title>\n',html(item));
fprintf(f,'<style>body{font:15px system-ui;margin:36px;color:#17212b}table{border-collapse:collapse;margin-bottom:28px}th,td{padding:7px 12px;text-align:right;border-bottom:1px solid #ddd;white-space:nowrap}th:first-child,td:first-child{text-align:left}h1{font-size:24px}h2{font-size:18px}</style>\n');
fprintf(f,'<h1>%s: %s</h1>\n',html(item),html(title));
fprintf(f,'<p>Levels: &deg;C. Rates: &deg;C per decade. Accelerations: &deg;C per decade squared. Unrounded values are in the companion CSV and MAT files.</p>\n');
for k=1:size(P,1)
 if strlength(string(P{k,1}))>0,fprintf(f,'<h2>%s</h2>\n',html(P{k,1}));end
 fprintf(f,'<table><thead><tr>');H=P{k,2};rows=P{k,3};
 for j=1:numel(H),fprintf(f,'<th>%s</th>',html(H{j}));end
 fprintf(f,'</tr></thead><tbody>\n');
 for i=1:size(rows,1)
  fprintf(f,'<tr>');for j=1:size(rows,2),s=char(string(rows{i,j}));if startsWith(s,'*'),s=['<b>' html(s(2:end)) '</b>'];else,s=html(s);end;fprintf(f,'<td>%s</td>',s);end;fprintf(f,'</tr>\n');
 end
 fprintf(f,'</tbody></table>\n');
end
clear c
f=fopen(fullfile(out,[item '.tex']),'w');assert(f>0);c=onCleanup(@()fclose(f));
fprintf(f,'%% Requires booktabs and longtable. Numbers generated by MATLAB.\n');
H=P{1,2};N=numel(H);
fprintf(f,'\\begingroup\\scriptsize\n\\begin{longtable}{l%s}\n',repmat('r',1,N-1));
fprintf(f,'\\caption{%s: %s}\\\\\n',tex(item),tex(title));
for k=1:size(P,1)
 H=P{k,2};rows=P{k,3};
 if strlength(string(P{k,1}))>0,fprintf(f,'\\multicolumn{%d}{l}{\\textbf{%s}}\\\\\n',N,tex(P{k,1}));end
 fprintf(f,'\\toprule\n%s \\\\\n\\midrule\n',strjoin(cellfun(@tex,H,'UniformOutput',false),' & '));
 for i=1:size(rows,1)
  cells=cell(1,N);
  for j=1:N,s=char(string(rows{i,j}));if startsWith(s,'*'),cells{j}=['\textbf{' tex(s(2:end)) '}'];else,cells{j}=tex(s);end,end
  fprintf(f,'%s \\\\\n',strjoin(cells,' & '));
 end
 fprintf(f,'\\bottomrule\n');
end
fprintf(f,'\\end{longtable}\n\\endgroup\n');
end
function s=html(v)
s=char(string(v));s=strrep(s,'&','&amp;');s=strrep(s,'<','&lt;');s=strrep(s,'>','&gt;');s=strrep(s,'"','&quot;');
end
function s=tex(v)
s=char(string(v));s=strrep(s,'\','\textbackslash{}');
for c={'&','%','_','#'},s=strrep(s,c{1},['\' c{1}]);end
s=strrep(s,'^','\textasciicircum{}');
end
